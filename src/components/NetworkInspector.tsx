import React from 'react';
import { Activity, Trash2, Clock, CheckCircle2, AlertCircle } from 'lucide-react';
import { ApiLogEntry } from '../types/task.ts';

interface NetworkInspectorProps {
  logs: ApiLogEntry[];
  onClearLogs: () => void;
}

export const NetworkInspector: React.FC<NetworkInspectorProps> = ({ logs, onClearLogs }) => {
  return (
    <div className="space-y-6 max-w-5xl mx-auto pb-12">
      <div className="bg-white border border-zinc-200 rounded-2xl p-6 sm:p-7 flex flex-col sm:flex-row items-start sm:items-center justify-between gap-4 shadow-xs">
        <div>
          <div className="flex items-center gap-2 text-xs text-zinc-500 mb-1">
            <span>Client-Server Telemetry</span>
            <span>·</span>
            <span>Live Network</span>
          </div>
          <h2 className="text-xl font-bold text-zinc-900 tracking-tight">
            REST API Network Inspector
          </h2>
          <p className="text-sm text-zinc-600 max-w-2xl mt-1 leading-relaxed">
            Live HTTP logs generated by user interactions (Add Task, Update Status, Delete, List). Inspect status codes, payloads, and roundtrip latency.
          </p>
        </div>

        {logs.length > 0 && (
          <button
            onClick={onClearLogs}
            className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg bg-zinc-50 hover:bg-zinc-100 text-xs font-medium text-zinc-700 border border-zinc-200 transition-colors"
          >
            <Trash2 className="w-3.5 h-3.5 text-zinc-500" />
            <span>Clear Logs</span>
          </button>
        )}
      </div>

      {logs.length === 0 ? (
        <div className="bg-white border border-zinc-200 rounded-2xl p-12 text-center max-w-md mx-auto shadow-xs">
          <Activity className="w-8 h-8 text-zinc-400 mx-auto mb-3" />
          <h3 className="text-sm font-semibold text-zinc-900 mb-1">No API calls recorded yet</h3>
          <p className="text-xs text-zinc-500">
            Create or edit a task from the Task Board, or test an endpoint in Planned API Routes to see requests here.
          </p>
        </div>
      ) : (
        <div className="space-y-3">
          {logs.map((log) => {
            const isSuccess = log.statusCode >= 200 && log.statusCode < 300;
            const methodBg =
              log.method === 'POST'
                ? 'bg-emerald-50 text-emerald-700 border-emerald-200'
                : log.method === 'GET'
                ? 'bg-sky-50 text-sky-700 border-sky-200'
                : log.method === 'PATCH'
                ? 'bg-amber-50 text-amber-700 border-amber-200'
                : 'bg-rose-50 text-rose-700 border-rose-200';

            return (
              <div
                key={log.id}
                className="bg-white border border-zinc-200 rounded-xl p-4 space-y-3 shadow-xs"
              >
                <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 border-b border-zinc-100 pb-2.5">
                  <div className="flex items-center gap-2.5 flex-wrap">
                    <span
                      className={`px-2 py-0.5 rounded font-mono text-xs font-bold border ${methodBg}`}
                    >
                      {log.method}
                    </span>
                    <span className="font-mono text-xs sm:text-sm font-semibold text-zinc-900">
                      {log.endpoint}
                    </span>
                    <span
                      className={`inline-flex items-center gap-1 px-2 py-0.5 rounded text-xs font-mono font-semibold ${
                        isSuccess
                          ? 'bg-emerald-50 text-emerald-700 border border-emerald-200'
                          : 'bg-rose-50 text-rose-700 border border-rose-200'
                      }`}
                    >
                      {isSuccess ? (
                        <CheckCircle2 className="w-3 h-3" />
                      ) : (
                        <AlertCircle className="w-3 h-3" />
                      )}
                      <span>{log.statusCode}</span>
                    </span>
                  </div>

                  <div className="flex items-center gap-3 text-xs text-zinc-500">
                    <span className="flex items-center gap-1 font-mono">
                      <Clock className="w-3 h-3 text-zinc-400" />
                      <span>{log.durationMs}ms</span>
                    </span>
                    <span className="font-mono">{new Date(log.timestamp).toLocaleTimeString()}</span>
                  </div>
                </div>

                <div className="grid grid-cols-1 md:grid-cols-2 gap-3 text-xs font-mono">
                  {log.requestPayload !== undefined && (
                    <div className="bg-zinc-50 p-2.5 rounded-lg border border-zinc-200">
                      <div className="text-[10px] uppercase font-bold text-zinc-500 mb-1">
                        Request Payload
                      </div>
                      <pre className="text-zinc-800 overflow-x-auto max-h-32 text-[11px] leading-tight">
                        {JSON.stringify(log.requestPayload, null, 2)}
                      </pre>
                    </div>
                  )}

                  <div
                    className={`bg-zinc-50 p-2.5 rounded-lg border border-zinc-200 ${
                      log.requestPayload === undefined ? 'md:col-span-2' : ''
                    }`}
                  >
                    <div className="text-[10px] uppercase font-bold text-zinc-500 mb-1">
                      Response Body
                    </div>
                    <pre
                      className={`overflow-x-auto max-h-32 text-[11px] leading-tight ${
                        isSuccess ? 'text-zinc-800' : 'text-rose-700'
                      }`}
                    >
                      {JSON.stringify(log.responsePayload, null, 2)}
                    </pre>
                  </div>
                </div>
              </div>
            );
          })}
        </div>
      )}
    </div>
  );
};
